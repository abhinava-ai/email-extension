// Builds Extension/chrome-dev from this source folder and keeps it in sync.
// Load chrome-dev in Chrome with "Load unpacked". Never edit files inside it:
// they are generated and get overwritten.
//
//   npm run dev         sync and watch, using the Hostinger API
//   npm run dev:local   sync and watch, using http://localhost:3000
//   add -- --once       build a single time and exit
const fs = require('node:fs');
const path = require('node:path');
const { execFileSync } = require('node:child_process');

const SOURCE = path.resolve(__dirname, '..');
const OUT = path.resolve(SOURCE, '..', 'chrome-dev');
const DEFAULT_API = 'https://peachpuff-barracuda-143070.hostingersite.com';
const SOURCE_API = 'http://localhost:3000';
const EXCLUDED = new Set([
  '.git', '.gitignore', 'node_modules', 'test-results', 'tests', 'scripts', 'src',
  'package.json', 'package-lock.json', 'README.md'
]);

// Runs only in the dev folder. The alarm wakes the service worker, which then
// reloads the extension when the watcher has published a new build stamp.
const DEV_RELOAD = `// Generated by scripts/dev-chrome.cjs. Exists only in the dev folder.
(() => {
  const ALARM = 'mtv-dev-reload';
  const KEY = 'mtv_dev_build_stamp';
  async function check() {
    const response = await fetch(chrome.runtime.getURL('dev-build.json'), { cache: 'no-store' });
    const { stamp } = await response.json();
    const stored = await chrome.storage.session.get(KEY);
    if (!stored[KEY]) await chrome.storage.session.set({ [KEY]: stamp });
    else if (stored[KEY] !== stamp) chrome.runtime.reload();
  }
  chrome.alarms.onAlarm.addListener((alarm) => {
    if (alarm.name === ALARM) check().catch((error) => console.warn('[dev reload]', error));
  });
  chrome.alarms.create(ALARM, { periodInMinutes: 0.05 });
  check().catch((error) => console.warn('[dev reload]', error));
})();
`;

function parseArgs(argv) {
  const apiIndex = argv.indexOf('--api');
  const api = (apiIndex >= 0 ? argv[apiIndex + 1] : DEFAULT_API || '').replace(/\/$/, '');
  if (!/^https?:\/\//.test(api)) throw new Error(`--api needs an http(s) URL, got "${api}"`);
  return { api, once: argv.includes('--once') };
}

function readSourceFiles(dir = SOURCE, prefix = '', files = new Map()) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (!prefix && EXCLUDED.has(entry.name)) continue;
    const rel = prefix ? `${prefix}/${entry.name}` : entry.name;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) readSourceFiles(full, rel, files);
    else files.set(rel, fs.readFileSync(full));
  }
  return files;
}

function applyDevChanges(files, api) {
  const origin = new URL(api).origin;
  const manifest = JSON.parse(files.get('manifest.json').toString('utf8'));
  manifest.name = `${manifest.name} (DEV)`;
  manifest.permissions = [...new Set([...manifest.permissions, 'alarms'])];
  manifest.host_permissions = [...new Set([...manifest.host_permissions, `${origin}/*`])];
  manifest.content_security_policy.extension_pages = manifest.content_security_policy.extension_pages
    .replace(/connect-src ([^;]*)/, (_, hosts) => `connect-src 'self' ${hosts} ${origin}`);
  files.set('manifest.json', Buffer.from(`${JSON.stringify(manifest, null, 2)}\n`));

  const config = files.get('supabase-config.js').toString('utf8');
  files.set('supabase-config.js', Buffer.from(config.split(SOURCE_API).join(api)));

  // Kept on line 1 so background.js line numbers still match the source.
  const background = files.get('background.js').toString('utf8');
  files.set('background.js', Buffer.from(`importScripts('dev-reload.js'); ${background}`));
  files.set('dev-reload.js', Buffer.from(DEV_RELOAD));
  return files;
}

function listOutFiles(dir = OUT, prefix = '', found = []) {
  if (!fs.existsSync(dir)) return found;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const rel = prefix ? `${prefix}/${entry.name}` : entry.name;
    if (entry.isDirectory()) listOutFiles(path.join(dir, entry.name), rel, found);
    else found.push(rel);
  }
  return found;
}

function removeEmptyDirs(dir = OUT) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    const full = path.join(dir, entry.name);
    removeEmptyDirs(full);
    if (fs.readdirSync(full).length === 0) fs.rmdirSync(full);
  }
}

function sync(api) {
  const files = applyDevChanges(readSourceFiles(), api);
  const changed = [];
  for (const [rel, content] of files) {
    const target = path.join(OUT, rel);
    if (fs.existsSync(target) && fs.readFileSync(target).equals(content)) continue;
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, content);
    changed.push(rel);
  }
  for (const rel of listOutFiles()) {
    if (rel === 'dev-build.json' || files.has(rel)) continue;
    fs.rmSync(path.join(OUT, rel));
    changed.push(`${rel} (removed)`);
  }
  removeEmptyDirs();
  // Written last so Chrome only reloads once the other files are in place.
  if (changed.length || !fs.existsSync(path.join(OUT, 'dev-build.json'))) {
    fs.writeFileSync(path.join(OUT, 'dev-build.json'), JSON.stringify({ stamp: new Date().toISOString() }));
  }
  return changed;
}

function buildAuth() {
  execFileSync(process.execPath, [path.join(__dirname, 'build-auth.cjs')], { cwd: SOURCE, stdio: 'inherit' });
}

function isIgnored(relative) {
  const top = String(relative || '').split(/[\\/]/)[0];
  return ['.git', 'node_modules', 'test-results', 'tests', 'scripts'].includes(top);
}

function watch(api) {
  let timer = null;
  let needsAuthBuild = false;
  const run = () => {
    try {
      if (needsAuthBuild) {
        needsAuthBuild = false;
        buildAuth();
      }
      const changed = sync(api);
      if (changed.length) console.log(`[${new Date().toLocaleTimeString()}] Updated: ${changed.join(', ')}`);
    } catch (error) {
      // Half-saved files can fail to parse. Keep watching; the next save retries.
      console.error(`[${new Date().toLocaleTimeString()}] Not synced: ${error.message}`);
    }
  };
  fs.watch(SOURCE, { recursive: true }, (_event, relative) => {
    if (isIgnored(relative)) return;
    if (String(relative).startsWith('src')) needsAuthBuild = true;
    clearTimeout(timer);
    timer = setTimeout(run, 300);
  });
  console.log('Watching for changes. Press Ctrl+C to stop.');
}

const { api, once } = parseArgs(process.argv.slice(2));
const changed = sync(api);
console.log(`Dev folder: ${OUT}`);
console.log(`API: ${api}`);
console.log(`Files updated: ${changed.length}`);
if (!once) watch(api);

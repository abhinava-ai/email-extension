// Hostinger builds only App/mail-template-vault, so the web app needs its own copy of the
// extension's formatting engine. Tests fail if the two ever differ.
const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const source = fs.readFileSync(path.join(root, 'Extension', 'outlook-template-vault', 'sanitizer.js'), 'utf8');
const output = `/* eslint-disable */\n// Generated by scripts/sync-sanitizer.cjs from the extension's sanitizer.js. Do not edit.\n${source}\nexport { TemplateSanitizer };\n`;
fs.writeFileSync(path.join(root, 'App', 'mail-template-vault', 'lib', 'template-sanitizer.js'), output);
console.log('Updated lib/template-sanitizer.js');
